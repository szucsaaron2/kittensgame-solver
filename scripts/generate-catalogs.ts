// Jobs and races: simple name lists, always in-scope.
function emitNameList(fileName: string, constName: string, typeName: string, names: string[]): void {
  const arr = names.map((n) => `"${n}"`).join(",\n  ");
  const content = `// AUTO-GENERATED by scripts/generate-catalogs.ts. Do not hand-edit.

export const ${constName}_NAMES = [
  ${arr},
] as const;

export type ${typeName} = (typeof ${constName}_NAMES)[number];
`;
  writeFileSync(resolve(OUT_DIR, fileName), content);
}

// eslint-disable-next-line @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-explicit-any
const jobs: string[] = (g.village.jobs ?? g.village.sim?.jobs ?? []).map((j: any) => j.name as string);
emitNameList("jobs.ts", "JOB", "JobName", jobs);

// eslint-disable-next-line @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-explicit-any
const races: string[] = (g.diplomacy.races ?? []).map((r: any) => r.name as string);
emitNameList("civs.ts", "CIV", "CivName", races);

// Planets — special: per-planet building dictionary.
// eslint-disable-next-line @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-assignment
const planets = g.space.planets ?? [];
// eslint-disable-next-line @typescript-eslint/no-explicit-any, @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-return, @typescript-eslint/no-unsafe-member-access
const planetNames: string[] = planets.map((p: any) => p.name as string);
const planetBuildingMeta: Record<string, Array<{ name: string; inScope: boolean }>> = {};
for (const p of planets) {
  // eslint-disable-next-line @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-assignment
  planetBuildingMeta[p.name as string] = entries(p.buildings);
}

const planetsContent = `// AUTO-GENERATED by scripts/generate-catalogs.ts. Do not hand-edit.

export const PLANET_NAMES = [
  ${planetNames.map((n) => `"${n}"`).join(",\n  ")},
] as const;

export type PlanetName = (typeof PLANET_NAMES)[number];

export interface PlanetBuildingMeta {
  inScope: boolean;
}

export const PLANET_BUILDING_META: Record<PlanetName, Record<string, PlanetBuildingMeta>> = {
${Object.entries(planetBuildingMeta)
  .map(
    ([planet, builds]) =>
      `  ${JSON.stringify(planet)}: {\n${builds
        .map((b) => `    ${JSON.stringify(b.name)}: { inScope: ${b.inScope} },`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
};

export const PLANET_BUILDING_NAMES: Record<PlanetName, readonly string[]> = {
${Object.entries(planetBuildingMeta)
  .map(
    ([planet, builds]) =>
      `  ${JSON.stringify(planet)}: [${builds.map((b) => `"${b.name}"`).join(", ")}] as const,`,
  )
  .join("\n")}
};
`;
writeFileSync(resolve(OUT_DIR, "planets.ts"), planetsContent);

// Per-civ pact tier max — populated where pacts exist.
// In Kittens Game, leviathans support the Mausoleum unicorn-relic pacts (no tiers in
// the current base game; pacts are applied as boolean activations). For now we set
// PACT_TIERS_MAX to 0 for everyone except known tiered pact races.
// Inspect g.religion.pacts at runtime if present.
// eslint-disable-next-line @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-assignment
const pactsArr = g.religion?.pactsManager?.pacts ?? g.religion?.pacts ?? [];
const pactCount = Array.isArray(pactsArr) ? pactsArr.length : 0;

const pactTiersMax: Record<string, number> = {};
for (const r of races) pactTiersMax[r] = 0;
// Leviathans: mausoleum pacts. Set tier max from pactCount if any exist; default 0
// otherwise. Refine as the model gets clearer.
if (pactCount > 0) pactTiersMax["leviathans"] = 0; // placeholder; current base has no tiers

function pactLines(rs: string[]): string {
  return rs.map((r) => `  ${JSON.stringify(r)}: ${pactTiersMax[r] ?? 0},`).join("\n");
}

const civsExtraContent = `// AUTO-GENERATED by scripts/generate-catalogs.ts. Do not hand-edit.

import type { CivName } from "./civs";

export const PACT_TIERS_MAX: Record<CivName, number> = {
${pactLines(races)}
};
`;

writeFileSync(resolve(OUT_DIR, "pacts.ts"), civsExtraContent);

