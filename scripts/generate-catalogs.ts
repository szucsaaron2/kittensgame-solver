// eslint-disable-next-line @typescript-eslint/no-explicit-any
function hasParagonOrKarma(entry: any): boolean {
  // eslint-disable-next-line @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-assignment
  const prices: unknown = entry?.prices ?? entry?.cost ?? [];
  if (!Array.isArray(prices)) return false;
  // eslint-disable-next-line @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-explicit-any
  return prices.some((p: any) => p?.name === "paragon" || p?.name === "karma");
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function entries(arr: any, categoryInScope = true): Array<{ name: string; inScope: boolean }> {
  // eslint-disable-next-line @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access, @typescript-eslint/no-unsafe-return
  return (arr ?? [])
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    .filter((x: any) => typeof x?.name === "string")
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    .map((x: any) => ({
      name: x.name as string,
      inScope: categoryInScope && !hasParagonOrKarma(x),
    }));
}

function emitCatalog(
  fileName: string,
  constName: string,
  typeName: string,
  data: Array<{ name: string; inScope: boolean }>,
): void {
  if (data.length === 0) {
    const content = `// AUTO-GENERATED by scripts/generate-catalogs.ts. Do not hand-edit.

export const ${constName}_NAMES = [] as const;

export type ${typeName} = never;

export interface ${typeName}Meta {
  inScope: boolean;
}

export const ${constName}_META: Record<string, ${typeName}Meta> = {};
`;
    writeFileSync(resolve(OUT_DIR, fileName), content);
    return;
  }
  const namesArr = data.map((d) => `"${d.name}"`).join(",\n  ");
  const metaEntries = data
    .map((d) => `  ${JSON.stringify(d.name)}: { inScope: ${d.inScope} },`)
    .join("\n");
  const content = `// AUTO-GENERATED by scripts/generate-catalogs.ts. Do not hand-edit.

export const ${constName}_NAMES = [
  ${namesArr},
] as const;

export type ${typeName} = (typeof ${constName}_NAMES)[number];

export interface ${typeName}Meta {
  inScope: boolean;
}

export const ${constName}_META: Record<${typeName}, ${typeName}Meta> = {
${metaEntries}
};
`;
  writeFileSync(resolve(OUT_DIR, fileName), content);
}

